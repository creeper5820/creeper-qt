from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

from core.config import REPO_ROOT, Config, ConfigError
from core.kotlin import KotlinFile
from core.model import CubicBezier, Dp, Double, Float, Int, Sp, Value
from core.resolve import SysEntry, SysRef, TypeScale

GENERATED_MARKER = "// GENERATED by tool/md3-token/generator.py. DO NOT EDIT."


@dataclass(frozen=True)
class MeasurementField:
    name: str
    type_name: str
    value: str


@dataclass(frozen=True)
class ColorField:
    name: str
    token: str | None
    scheme_field: str | None
    opacity: str | None


def cpp_name(name: str) -> str:
    return f"k{name}"


def _number(value: float) -> str:
    if value.is_integer():
        return str(int(value))
    return repr(value)


def _double(value: float) -> str:
    text = _number(value)
    if "." not in text and "e" not in text:
        text += ".0"
    return text


def _dp(value: float) -> str:
    if value < 0:
        return f"Dp {{ {_number(value)} }}"
    return f"{_number(value)}_dp"


def _sp(value: float) -> str:
    if value < 0:
        return f"Sp {{ {_number(value)} }}"
    return f"{_number(value)}_sp"


def render_value(value: Value | SysRef) -> str:
    if isinstance(value, SysRef):
        return f"sys::{value.kind}::{cpp_name(value.name)}"
    if isinstance(value, Dp):
        return _dp(value.value)
    if isinstance(value, Sp):
        return _sp(value.value)
    if isinstance(value, (Float, Double)):
        return _double(value.value)
    if isinstance(value, Int):
        return str(value.value)
    if isinstance(value, CubicBezier):
        arguments = ", ".join(_double(number) for number in (value.a, value.b, value.c, value.d))
        return f"CubicBezierSolution {{ {arguments} }}"
    raise ConfigError(f"cannot render value {type(value).__name__}")


def _src_relative(config: Config) -> Path:
    source_root = (REPO_ROOT / "src").resolve()
    try:
        return config.output.resolve().relative_to(source_root)
    except ValueError:
        raise ConfigError(
            f"{config.output}: output must be under {source_root}") from None


def include_path(config: Config, *parts: str) -> str:
    return "/".join((*_src_relative(config).parts, *parts))


def source_label(config: Config, path: Path) -> str:
    resolved = path.resolve()
    candidates = []
    for alias, relative in config.modules.items():
        root = (config.cache / relative).resolve()
        if root == resolved or root in resolved.parents:
            candidates.append((len(root.parts), alias, root))
    if candidates:
        _, alias, root = max(candidates)
        return f"{alias}:{resolved.relative_to(root).as_posix()}"
    try:
        return resolved.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path)


def render_header(config: Config, sources: tuple[KotlinFile, ...]) -> list[str]:
    lines = [GENERATED_MARKER, f"// androidx {config.androidx.commit}"]
    for source in sources:
        label = source_label(config, source.path)
        if source.version is not None:
            label += f" (VERSION {source.version})"
        lines.append(f"// {label}")
    lines.append("#pragma once")
    return lines


def component_path(config: Config, namespace: str) -> Path:
    return config.output / namespace / "values.hh"


def measurements_path(config: Config, namespace: str) -> Path:
    return config.output / namespace / "measurements.hh"


def colors_path(config: Config, namespace: str) -> Path:
    return config.output / namespace / "colors.hh"


def defaults_path(config: Config, namespace: str) -> Path:
    return config.output / namespace / "defaults.hh"


def sys_path(config: Config, kind: str) -> Path:
    return config.output / "sys" / f"{kind}.hh"


def render_component(
        config: Config, path: Path, namespace: str,
        values: tuple[tuple[str, Value | SysRef], ...],
        sources: tuple[KotlinFile, ...]) -> str:
    kinds = sorted({value.kind for _, value in values if isinstance(value, SysRef)})
    includes = [f'#include "{include_path(config, "sys", f"{kind}.hh")}"' for kind in kinds]
    includes.append(f'#include "{include_path(config, "unit.hh")}"')
    if any(isinstance(value, CubicBezier) for _, value in values):
        includes.append('#include "creeper-qt/utility/math/cubic-bezier.hh"')

    lines = render_header(config, sources)
    lines.append("")
    lines.extend(includes)
    lines.append("")
    lines.append(f"namespace creeper::token::{namespace} {{")
    lines.append("")
    for name, value in values:
        lines.append(f"constexpr inline auto {cpp_name(name)} = {render_value(value)};")
    lines.append("")
    lines.append("}")
    lines.append("")
    return format_cpp(path, "\n".join(lines))


def render_measurements(
        config: Config, path: Path, namespace: str,
        measurements: tuple[MeasurementField, ...],
        sources: tuple[KotlinFile, ...]) -> str:
    lines = render_header(config, sources)
    lines.append("")
    lines.append(f'#include "{include_path(config, namespace, "values.hh")}"')
    lines.append("")
    lines.append(f"namespace creeper::token::{namespace} {{")
    lines.append("")
    lines.append("struct Measurements {")
    for measurement in measurements:
        lines.append(
            f"    {measurement.type_name} {measurement.name} = {measurement.value};")
    lines.append("")
    lines.append(
        "    friend auto dsl_invoke(auto& self, const Measurements& measurements) -> void")
    lines.append("        requires requires { self.setMeasurements(measurements); }")
    lines.append("    {")
    lines.append("        self.setMeasurements(measurements);")
    lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("}")
    lines.append("")
    return format_cpp(path, "\n".join(lines))


def render_colors(
        config: Config, path: Path, namespace: str,
        colors: tuple[ColorField, ...],
        sources: tuple[KotlinFile, ...]) -> str:
    lines = render_header(config, sources)
    lines.append("")
    lines.append(f'#include "{include_path(config, "color.hh")}"')
    lines.append("")
    lines.append(f"namespace creeper::token::{namespace} {{")
    lines.append("")
    lines.append("struct Colors {")
    for color in colors:
        lines.append(f"    Color {color.name};")
    lines.append("")
    lines.append(
        "    friend auto dsl_invoke(auto& self, const Colors& colors) -> void")
    lines.append("        requires requires { self.setColors(colors); }")
    lines.append("    {")
    lines.append("        self.setColors(colors);")
    lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("}")
    lines.append("")
    return format_cpp(path, "\n".join(lines))


def render_defaults(
        config: Config, path: Path, namespace: str,
        values: tuple[str, ...],
        colors: tuple[ColorField, ...] | None,
        sources: tuple[KotlinFile, ...]) -> str:
    lines = render_header(config, sources)
    lines.append("")
    if colors is not None:
        lines.append(
            f'#include "{include_path(config, namespace, "colors.hh")}"')
    lines.append(f'#include "{include_path(config, namespace, "values.hh")}"')
    if colors is not None:
        lines.append('#include "creeper-qt/utility/theme/color-scheme.hh"')
    lines.append("")
    lines.append(f"namespace creeper::token::{namespace} {{")
    lines.append("")
    lines.append("struct Defaults {")
    for name in values:
        lines.append(
            f"    constexpr static auto k{name} = {namespace}::k{name};")
    if colors is not None:
        lines.append("")
        lines.append(
            "    static auto mapColors(const ColorScheme& scheme, Colors& colors) -> void {")
        for color in colors:
            if color.token is None:
                lines.append(f"        colors.{color.name} = Qt::transparent;")
                continue
            if color.opacity is None:
                lines.append(
                    f"        colors.{color.name} = scheme.{color.scheme_field};")
            else:
                lines.append(
                    f"        colors.{color.name} = {{ scheme.{color.scheme_field}, "
                    f"k{color.opacity} }};")
        lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("}")
    lines.append("")
    return format_cpp(path, "\n".join(lines))


def render_sys(
        config: Config, kind: str, entries: tuple[SysEntry, ...],
        sources: tuple[KotlinFile, ...]) -> str:
    path = sys_path(config, kind)
    lines = render_header(config, sources)
    lines.append("")
    lines.append(f'#include "{include_path(config, "unit.hh")}"')
    lines.append("")
    lines.append(f"namespace creeper::token::sys::{kind} {{")
    lines.append("")
    if kind == "typography":
        lines.append("struct TypeScale {")
        lines.append("    Sp size;")
        lines.append("    Sp line_height;")
        lines.append("    Sp tracking;")
        lines.append("    int weight;")
        lines.append("};")
        lines.append("")
        for entry in entries:
            scale = entry.value
            if not isinstance(scale, TypeScale):
                raise ConfigError(f"cannot render typography entry {entry.name}")
            lines.append(f"constexpr inline auto {cpp_name(entry.name)} = TypeScale {{")
            lines.append(f"    .size = {render_value(scale.size)},")
            lines.append(f"    .line_height = {render_value(scale.line_height)},")
            lines.append(f"    .tracking = {render_value(scale.tracking)},")
            lines.append(f"    .weight = {scale.weight},")
            lines.append("};")
            lines.append("")
    else:
        for entry in entries:
            lines.append(
                f"constexpr inline auto {cpp_name(entry.name)} = {render_value(entry.value)};")
        lines.append("")
    lines.append("}")
    lines.append("")
    return format_cpp(path, "\n".join(lines))


def format_cpp(path: Path, text: str) -> str:
    command = [
        "clang-format",
        f"--style=file:{REPO_ROOT / '.clang-format'}",
        f"--assume-filename={path}",
    ]
    try:
        result = subprocess.run(
            command, input=text, capture_output=True, text=True, check=False)
    except FileNotFoundError:
        raise ConfigError("clang-format not found") from None
    if result.returncode != 0:
        raise ConfigError(
            f"{path}: clang-format failed: {result.stderr.strip()}")
    return result.stdout
